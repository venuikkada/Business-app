-- 004 Sales and purchase documents. One header table + one line table per side.
-- Sales flow:     quotation -> sales_order -> invoice -> payment -> credit_note
-- Purchase flow:  purchase_order -> goods_receipt -> supplier_bill -> payment -> debit_note
-- source_doc_id links each document to the one it was converted from.

CREATE TABLE sales_documents (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id         BIGINT UNSIGNED NOT NULL,
  branch_id         BIGINT UNSIGNED NOT NULL,
  doc_type          VARCHAR(20)  NOT NULL,
  number            VARCHAR(16)  NOT NULL COMMENT 'GST allows max 16 chars, unique per FY',
  fy                CHAR(7)      NOT NULL,
  doc_date          DATE         NOT NULL,
  due_date          DATE         NULL,
  valid_until       DATE         NULL COMMENT 'quotations',
  party_id          BIGINT UNSIGNED NULL COMMENT 'NULL = walk-in cash customer (B2C)',
  party_snapshot    JSON         NULL COMMENT 'name, GSTIN, address as printed',
  supply_type       VARCHAR(8)   NOT NULL DEFAULT 'B2C' COMMENT 'B2B, B2CL, B2CS, EXPORT, SEZ',
  place_of_supply   CHAR(2)      NOT NULL,
  reverse_charge    TINYINT(1)   NOT NULL DEFAULT 0,
  price_includes_tax TINYINT(1)  NOT NULL DEFAULT 1,
  status            VARCHAR(16)  NOT NULL DEFAULT 'draft',
  subtotal          DECIMAL(14,2) NOT NULL DEFAULT 0,
  discount_total    DECIMAL(14,2) NOT NULL DEFAULT 0,
  taxable_total     DECIMAL(14,2) NOT NULL DEFAULT 0,
  cgst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  sgst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  igst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  cess_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  round_off         DECIMAL(6,2)  NOT NULL DEFAULT 0,
  grand_total       DECIMAL(14,2) NOT NULL DEFAULT 0,
  amount_paid       DECIMAL(14,2) NOT NULL DEFAULT 0,
  balance_due       DECIMAL(14,2) NOT NULL DEFAULT 0,
  source_doc_id     BIGINT UNSIGNED NULL,
  channel           VARCHAR(12)  NOT NULL DEFAULT 'counter' COMMENT 'counter, dine_in, takeaway, delivery, online',
  sector_ref_type   VARCHAR(30)  NULL COMMENT 'e.g. restaurant_order, hotel_folio, project',
  sector_ref_id     BIGINT UNSIGNED NULL,
  notes             VARCHAR(1000) NULL,
  terms             VARCHAR(2000) NULL,
  -- FUTURE: e-invoice (IRN) and e-way bill
  irn               CHAR(64)     NULL,
  irn_ack_no        VARCHAR(20)  NULL,
  irn_ack_date      DATETIME     NULL,
  irn_signed_qr     TEXT         NULL,
  irn_status        VARCHAR(12)  NULL,
  eway_bill_no      VARCHAR(12)  NULL,
  eway_bill_valid_until DATETIME NULL,
  transport_details JSON         NULL,
  -- offline billing
  client_uuid       CHAR(36)     NULL COMMENT 'set by the offline app; makes sync idempotent',
  offline_created_at DATETIME(3) NULL,
  pdf_file_id       BIGINT UNSIGNED NULL,
  created_by        BIGINT UNSIGNED NULL,
  cancelled_at      DATETIME(3)  NULL,
  cancelled_by      BIGINT UNSIGNED NULL,
  cancel_reason     VARCHAR(255) NULL,
  created_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_sales_documents_tenant_id (tenant_id, id),
  UNIQUE KEY uq_sales_documents_number (tenant_id, doc_type, fy, number),
  UNIQUE KEY uq_sales_documents_client (tenant_id, client_uuid),
  KEY ix_sales_documents_list (tenant_id, doc_type, doc_date),
  KEY ix_sales_documents_party (tenant_id, party_id, doc_date),
  KEY ix_sales_documents_branch (tenant_id, branch_id, doc_date),
  KEY ix_sales_documents_due (tenant_id, status, due_date),
  CONSTRAINT fk_sales_documents_branch FOREIGN KEY (tenant_id, branch_id) REFERENCES branches(tenant_id, id),
  CONSTRAINT fk_sales_documents_party FOREIGN KEY (tenant_id, party_id) REFERENCES parties(tenant_id, id),
  CONSTRAINT fk_sales_documents_source FOREIGN KEY (tenant_id, source_doc_id) REFERENCES sales_documents(tenant_id, id),
  CONSTRAINT fk_sales_documents_pdf FOREIGN KEY (tenant_id, pdf_file_id) REFERENCES files(tenant_id, id),
  CONSTRAINT ck_sales_documents_type CHECK (doc_type IN ('quotation','sales_order','delivery_challan','invoice','credit_note')),
  CONSTRAINT ck_sales_documents_status CHECK (status IN ('draft','sent','accepted','rejected','expired','confirmed','issued','partially_paid','paid','cancelled','converted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sales_document_lines (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id      BIGINT UNSIGNED NOT NULL,
  document_id    BIGINT UNSIGNED NOT NULL,
  line_no        SMALLINT UNSIGNED NOT NULL,
  item_id        BIGINT UNSIGNED NULL,
  variant_id     BIGINT UNSIGNED NULL,
  batch_id       BIGINT UNSIGNED NULL,
  description    VARCHAR(300) NOT NULL,
  hsn_sac        VARCHAR(8)   NULL,
  qty            DECIMAL(14,3) NOT NULL,
  unit_code      VARCHAR(10)  NOT NULL DEFAULT 'NOS',
  rate           DECIMAL(14,4) NOT NULL,
  discount_pct   DECIMAL(6,3)  NOT NULL DEFAULT 0,
  discount_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  taxable_value  DECIMAL(14,2) NOT NULL,
  gst_rate       DECIMAL(5,2)  NOT NULL DEFAULT 0,
  cgst           DECIMAL(14,2) NOT NULL DEFAULT 0,
  sgst           DECIMAL(14,2) NOT NULL DEFAULT 0,
  igst           DECIMAL(14,2) NOT NULL DEFAULT 0,
  cess           DECIMAL(14,2) NOT NULL DEFAULT 0,
  line_total     DECIMAL(14,2) NOT NULL,
  cost_price     DECIMAL(14,4) NULL COMMENT 'for profit by item',
  serial_ids     JSON          NULL,
  meta           JSON          NULL COMMENT 'modifiers, measurements, room nights ...',
  PRIMARY KEY (id),
  UNIQUE KEY uq_sdl_line (tenant_id, document_id, line_no),
  KEY ix_sdl_item (tenant_id, item_id),
  CONSTRAINT fk_sdl_document FOREIGN KEY (tenant_id, document_id) REFERENCES sales_documents(tenant_id, id),
  CONSTRAINT fk_sdl_item FOREIGN KEY (tenant_id, item_id) REFERENCES items(tenant_id, id),
  CONSTRAINT fk_sdl_variant FOREIGN KEY (tenant_id, variant_id) REFERENCES item_variants(tenant_id, id),
  CONSTRAINT fk_sdl_batch FOREIGN KEY (tenant_id, batch_id) REFERENCES batches(tenant_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE purchase_documents (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id         BIGINT UNSIGNED NOT NULL,
  branch_id         BIGINT UNSIGNED NOT NULL,
  doc_type          VARCHAR(20)  NOT NULL,
  number            VARCHAR(20)  NOT NULL COMMENT 'our number',
  supplier_bill_no  VARCHAR(40)  NULL COMMENT 'number printed on the supplier bill',
  fy                CHAR(7)      NOT NULL,
  doc_date          DATE         NOT NULL,
  due_date          DATE         NULL,
  party_id          BIGINT UNSIGNED NOT NULL,
  place_of_supply   CHAR(2)      NOT NULL,
  reverse_charge    TINYINT(1)   NOT NULL DEFAULT 0,
  itc_eligible      TINYINT(1)   NOT NULL DEFAULT 1,
  status            VARCHAR(16)  NOT NULL DEFAULT 'draft',
  subtotal          DECIMAL(14,2) NOT NULL DEFAULT 0,
  discount_total    DECIMAL(14,2) NOT NULL DEFAULT 0,
  taxable_total     DECIMAL(14,2) NOT NULL DEFAULT 0,
  cgst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  sgst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  igst_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  cess_total        DECIMAL(14,2) NOT NULL DEFAULT 0,
  round_off         DECIMAL(6,2)  NOT NULL DEFAULT 0,
  grand_total       DECIMAL(14,2) NOT NULL DEFAULT 0,
  amount_paid       DECIMAL(14,2) NOT NULL DEFAULT 0,
  balance_due       DECIMAL(14,2) NOT NULL DEFAULT 0,
  source_doc_id     BIGINT UNSIGNED NULL,
  notes             VARCHAR(1000) NULL,
  attachment_file_id BIGINT UNSIGNED NULL,
  created_by        BIGINT UNSIGNED NULL,
  cancelled_at      DATETIME(3)  NULL,
  cancel_reason     VARCHAR(255) NULL,
  created_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_purchase_documents_tenant_id (tenant_id, id),
  UNIQUE KEY uq_purchase_documents_number (tenant_id, doc_type, fy, number),
  KEY ix_purchase_documents_list (tenant_id, doc_type, doc_date),
  KEY ix_purchase_documents_party (tenant_id, party_id, doc_date),
  KEY ix_purchase_documents_supplier_bill (tenant_id, party_id, supplier_bill_no),
  CONSTRAINT fk_purchase_documents_branch FOREIGN KEY (tenant_id, branch_id) REFERENCES branches(tenant_id, id),
  CONSTRAINT fk_purchase_documents_party FOREIGN KEY (tenant_id, party_id) REFERENCES parties(tenant_id, id),
  CONSTRAINT fk_purchase_documents_source FOREIGN KEY (tenant_id, source_doc_id) REFERENCES purchase_documents(tenant_id, id),
  CONSTRAINT fk_purchase_documents_file FOREIGN KEY (tenant_id, attachment_file_id) REFERENCES files(tenant_id, id),
  CONSTRAINT ck_purchase_documents_type CHECK (doc_type IN ('purchase_order','goods_receipt','supplier_bill','debit_note')),
  CONSTRAINT ck_purchase_documents_status CHECK (status IN ('draft','sent','partially_received','received','issued','partially_paid','paid','cancelled','converted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

