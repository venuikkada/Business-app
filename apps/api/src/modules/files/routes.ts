import multer from "multer";
import { z } from "zod";
import { ApiRouter, idParam } from "../../http/router.js";
import { TenantDb, withTx } from "../../db/pool.js";
import { badRequest, notFound } from "../../lib/errors.js";
import { audit } from "../audit/service.js";
import { MAX_UPLOAD_BYTES, diskPath, saveFile, validateUpload } from "./storage.js";

export const fileRoutes = new ApiRouter("");
const r = fileRoutes;

// Files are held in memory (max 5 MB) so they can be checked before anything touches the disk.
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: MAX_UPLOAD_BYTES, files: 1, fields: 5 } }).single("file");
const uploadMw = (req: any, res: any, next: any) =>
  upload(req, res, (err: any) => {
    if (err?.code === "LIMIT_FILE_SIZE") return next(badRequest("file_too_large", "File is too large. Maximum is 5 MB."));
    if (err) return next(badRequest("upload_failed", "Upload failed. Try again."));
    next();
  });

/** Business logo (PNG/JPG/WebP, max 1 MB). */
r.post("/tenant/logo", { access: { perm: "settings.edit" }, before: [uploadMw], allowWhenExpired: true }, async ({ req, ctx }) => {
  const f = (req as any).file as Express.Multer.File | undefined;
  if (!f) throw badRequest("file_required", "Choose a file to upload.");
  const mime = validateUpload("logo", f.buffer);
  return withTx(async (conn) => {
    const tdb = new TenantDb(conn, ctx.tenantId);
    const before = await tdb.one("SELECT logo_file_id FROM tenants WHERE id = :tenantId FOR UPDATE");
    const saved = await saveFile(tdb, { kind: "logo", buffer: f.buffer, mime, originalName: f.originalname, createdBy: ctx.userId });
    await tdb.exec("UPDATE tenants SET logo_file_id = :fid WHERE id = :tenantId", { fid: saved.id });
    await audit(tdb, ctx, {
      action: "update", entityType: "tenant", entityId: ctx.tenantId, summary: "Changed business logo",
      before: { logo_file_id: before?.logo_file_id ?? null }, after: { logo_file_id: saved.id },
    });
    return { fileId: saved.id };
  });
});

/** Generic attachment upload (bills, ID proofs). The caller links the returned id. */
r.post(
  "/files",
  { access: { perm: ["items.edit", "expenses.create", "employees.edit", "purchases.create", "settings.edit"] }, before: [uploadMw] },
  async ({ req, ctx }) => {
    const f = (req as any).file as Express.Multer.File | undefined;
    if (!f) throw badRequest("file_required", "Choose a file to upload.");
    const kind = z.enum(["item_image", "document", "employee_doc", "attachment"]).parse(req.body?.kind ?? "attachment");
    const mime = validateUpload(kind, f.buffer);
    const saved = await saveFile(ctx.tdb, { kind, buffer: f.buffer, mime, originalName: f.originalname, createdBy: ctx.userId });
    return { fileId: saved.id, mimeType: mime, size: f.buffer.length };
  },
);

/** Download: only members of the same business; never served from a public folder. */
r.get("/files/:id", { access: { perm: "any_member" } }, async ({ params, ctx, res }) => {
  const id = idParam(params);
  const f = await ctx.tdb.one(
    "SELECT kind, storage_path, original_name, mime_type FROM files WHERE tenant_id = :tenantId AND id = :id AND deleted_at IS NULL",
    { id },
  );
  if (!f) throw notFound("File");
  // Payslips, exports and backups need stronger permissions than a logo.
  const needs: Record<string, string> = { payslip: "payroll.view", export: "data.export", backup: "data.export", employee_doc: "employees.view" };
  if (needs[f.kind] && !ctx.permissions.has(needs[f.kind]!) && !(f.kind === "export" && ctx.permissions.has("audit.export"))) throw notFound("File");
  res.setHeader("Content-Type", f.mime_type);
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.setHeader("Cache-Control", "private, max-age=300");
  res.setHeader("Content-Disposition", `${f.mime_type.startsWith("image/") ? "inline" : "attachment"}; filename="${encodeURIComponent(f.original_name)}"`);
  res.setHeader("Content-Security-Policy", "default-src 'none'; img-src 'self'; style-src 'unsafe-inline'; sandbox");
  await new Promise<void>((resolve, reject) =>
    // dotfiles: "allow" — the path is generated by the server, never by the user.
    res.sendFile(diskPath(f.storage_path), { dotfiles: "allow" }, (err) => (err && !res.headersSent ? reject(notFound("File")) : resolve())),
  );
});
